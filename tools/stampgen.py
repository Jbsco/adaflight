#!/usr/bin/env python3
"""Generate the body of the image's build stamp: the date and time of this build.

usage: stampgen.py <output .adb>

The date reads as "Mmm dd yyyy" and the time as "hh:mm:ss", local time, the forms the compiler's own
compilation date and time take. SOURCE_DATE_EPOCH in the environment sets the moment instead. Every build
writes it anew; only this body depends on it, so its users do not recompile.
"""
import os
import sys
import time

MONTHS = ("Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec")


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    epoch = os.environ.get("SOURCE_DATE_EPOCH")
    t = time.gmtime(int(epoch)) if epoch else time.localtime()
    date = f"{MONTHS[t.tm_mon - 1]} {t.tm_mday:02d} {t.tm_year:04d}"
    clock = f"{t.tm_hour:02d}:{t.tm_min:02d}:{t.tm_sec:02d}"
    text = ("--  The date and time of this build, generated by tools/stampgen.py. Do not edit.\n"
            "package body Adaflight.STM32.Build_Stamp is\n"
            f"   function Build_Date return String is (\"{date}\");\n"
            f"   function Build_Time return String is (\"{clock}\");\n"
            "end Adaflight.STM32.Build_Stamp;\n")
    os.makedirs(os.path.dirname(sys.argv[1]) or ".", exist_ok=True)
    with open(sys.argv[1], "w") as f:
        f.write(text)


if __name__ == "__main__":
    main()
